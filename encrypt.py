def read_password():
    password = os.environ.get("WEDDING_PASSWORD")
    if password:
        return password
    password = getpass.getpass("Website password: ")
    if not password:
        sys.exit("No password entered.")
    if getpass.getpass("Type it again: ") != password:
        sys.exit("Passwords didn't match.")
    return password


def derive_key_material(password: str, salt: bytes) -> bytes:
    return hashlib.pbkdf2_hmac("sha256", password.encode("utf-8"), salt, ITERATIONS, dklen=64)


def encrypt(plaintext: bytes, material: bytes, salt: bytes) -> dict:
    # Every page shares the salt (so one unlock key opens them all) but gets its own IV.
    iv = os.urandom(16)
    aes_key, mac_key = material[:32], material[32:]

    result = subprocess.run(
        ["openssl", "enc", "-aes-256-cbc", "-K", aes_key.hex(), "-iv", iv.hex()],
        input=plaintext, capture_output=True, check=True,
    )
    ciphertext = result.stdout
    mac = hmac.new(mac_key, iv + ciphertext, hashlib.sha256).digest()

    b64 = lambda b: base64.b64encode(b).decode("ascii")
    return {"iterations": ITERATIONS, "salt": b64(salt), "iv": b64(iv), "mac": b64(mac), "data": b64(ciphertext)}


def page_title(source_html: str) -> str:
    match = re.search(r"<title>(.*?)</title>", source_html, re.S)
    return match.group(1).strip() if match else "Subhrodeep &amp; Cindy"


def main():
    missing = [src for src, _ in PAGES if not (HERE / src).exists()]
    if missing:
        sys.exit(f"Can't find {', '.join(missing)}. These are the readable pages this script encrypts.")

    salt = os.urandom(16)
    material = derive_key_material(read_password(), salt)
    for src, out in PAGES:
        source = (HERE / src).read_text(encoding="utf-8")
        payload = encrypt(source.encode("utf-8"), material, salt)
        page = GATE.replace("/*TITLE*/", page_title(source)).replace("/*PAYLOAD*/", json.dumps(payload))
        (HERE / out).write_text(page, encoding="utf-8")
        print(f"Wrote {out} ({(HERE / out).stat().st_size // 1024} KB)")
    print("Upload/commit these files to publish.")


if __name__ == "__main__":
    main()
